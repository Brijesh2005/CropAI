CROP_PROFILES.Rice = CROP_PROFILES.Paddy;

export function getCropProfile(cropName) {
  if (!cropName) return CROP_PROFILES.Arecanut;
  const clean = cropName.trim();
  if (CROP_PROFILES[clean]) return CROP_PROFILES[clean];
  
  const lower = clean.toLowerCase();
  for (const [key, val] of Object.entries(CROP_PROFILES)) {
    if (!val) continue;
    if (key.toLowerCase() === lower || val.name.toLowerCase().includes(lower) || lower.includes(key.toLowerCase())) {
      return val;
    }
  }

  if (lower.includes('rice') || lower.includes('paddy') || lower.includes('bhatta')) return CROP_PROFILES.Paddy;
  if (lower.includes('areca') || lower.includes('supari') || lower.includes('adike')) return CROP_PROFILES.Arecanut;
  if (lower.includes('coco') && !lower.includes('nut')) return CROP_PROFILES.Cocoa;
  if (lower.includes('coconut') || lower.includes('tengu')) return CROP_PROFILES.Coconut;
  if (lower.includes('pepper') || lower.includes('menasu')) return CROP_PROFILES.Pepper;
  if (lower.includes('cashew') || lower.includes('geru') || lower.includes('godambi')) return CROP_PROFILES.Cashew;
  if (lower.includes('banana') || lower.includes('bale')) return CROP_PROFILES.Banana;
  if (lower.includes('rubber')) return CROP_PROFILES.Rubber;
  if (lower.includes('peanut') || lower.includes('groundnut') || lower.includes('kadale')) return CROP_PROFILES.Groundnut;
  if (lower.includes('ginger') || lower.includes('shunti')) return CROP_PROFILES.Ginger;
  if (lower.includes('cardam') || lower.includes('elakki')) return CROP_PROFILES.Cardamum;
  if (lower.includes('coffee') || lower.includes('kafi')) return CROP_PROFILES.Coffee;

  return CROP_PROFILES.Arecanut;
}

